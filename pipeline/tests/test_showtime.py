class ScheduleTest(unittest.TestCase):
    def test_real_sentences(self):
        for text, s, e, want in CASES:
            with self.subTest(text=text[:40]):
                self.assertEqual(schedule(text, D(s), D(e)), want)

    def test_weekly_pattern_long_run(self):
        # 장기 공연: 수목금 저녁, 토 낮, 일 낮, 월·화 공연 없음
        got = schedule("수목금 19시 30분 / 토 15시, 19시 / 일 14시", D("2026-12-07"), D("2026-12-13"))
        self.assertEqual(got, {"2026-12-09": "19:30", "2026-12-10": "19:30", "2026-12-11": "19:30",
                               "2026-12-12": "15:00", "2026-12-13": "14:00"})

    def test_unknown_time_is_dropped(self):
        # 시간이 없으면 지어내지 않는다
        self.assertEqual(schedule("", D("2026-10-17"), D("2026-10-18")), {})
        self.assertEqual(schedule("추후 공지", D("2026-10-17"), D("2026-10-18")), {})

    def test_times_are_evening_plausible(self):
        # '6시'처럼 오전/오후가 없으면 저녁, 공연 시각은 9~23시만 허용
        self.assertEqual(schedule("토 6시", D("2026-12-12"), D("2026-12-12")), {"2026-12-12": "18:00"})
        self.assertEqual(schedule("토 3시", D("2026-12-12"), D("2026-12-12")), {"2026-12-12": "15:00"})


